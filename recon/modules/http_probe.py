@dataclass
class WebFingerprint:
    """Aggregated HTTP fingerprint for a single target."""
    target: str
    port: int
    scheme: str
    status_code: int = 0
    server: str = ""
    waf: str = ""
    cdn: str = ""
    technologies: list[str] = field(default_factory=list)
    security_header_issues: list[dict[str, str]] = field(default_factory=list)
    interesting_paths: list[dict[str, Any]] = field(default_factory=list)
    allowed_methods: list[str] = field(default_factory=list)
    cookies: list[dict[str, Any]] = field(default_factory=list)
    redirect_chain: list[str] = field(default_factory=list)
    robots_entries: list[str] = field(default_factory=list)
    version_disclosures: list[str] = field(default_factory=list)
    all_headers: dict[str, str] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "target": self.target,
            "port": self.port,
            "scheme": self.scheme,
            "status_code": self.status_code,
            "server": self.server,
            "waf": self.waf,
            "cdn": self.cdn,
            "technologies": self.technologies,
            "security_header_issues": self.security_header_issues,
            "interesting_paths": self.interesting_paths,
            "allowed_methods": self.allowed_methods,
            "version_disclosures": self.version_disclosures,
        }


